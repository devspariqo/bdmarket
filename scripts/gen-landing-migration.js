/**
 * Generate prisma/add-landing-pages.sql — the statements that add the landing
 * page table to a database that already exists.
 *
 *   node scripts/gen-landing-migration.js
 *
 * `fix-column-lengths.sql` only widens columns. A database created before the
 * landing page feature has no `LandingPage` table at all, so without this the
 * admin's Landing Pages screen 500s on a live site. Re-importing `schema.sql`
 * would drop every table instead, which is not an option for a store with orders.
 *
 * Derived from the generated DDL rather than written by hand, so it cannot drift
 * from the schema.
 */
const fs = require('fs');

const ddl = fs.readFileSync('prisma/schema.sql', 'utf8');

const table = ddl.match(/CREATE TABLE `LandingPage` \([\s\S]*?\n\)/);
if (!table) {
  console.error('CREATE TABLE `LandingPage` not found in prisma/schema.sql — run `npm run db:sql` first.');
  process.exit(1);
}

// The indexes are separate statements in the dump; pick up the ones for this table.
const indexes = [];
const idxRe = /CREATE (UNIQUE )?INDEX `(LandingPage_\w+)` ON `LandingPage`\(([^)]*)\)/g;
let m;
while ((m = idxRe.exec(ddl))) {
  indexes.push(`CREATE ${m[1] ? 'UNIQUE ' : ''}INDEX \`${m[2]}\` ON \`LandingPage\`(${m[3]});`);
}

const header = `-- Add the landing page table to an existing database
--
-- Run this in hPanel -> Databases -> phpMyAdmin -> select your database -> SQL
-- tab, before using Admin -> Growth -> Landing Pages on a site that is already
-- live. Without it that screen fails with
--   The table 'main.LandingPage' does not exist
--
-- A fresh install does NOT need this: prisma/schema.sql and
-- prisma/schema-with-demo.sql already create the table.
--
-- Non-destructive: it adds a table and one nullable column. No existing row is
-- touched. Orders are never deleted with a page — Order.landingPageId is
-- ON DELETE SET NULL, so removing a funnel keeps its orders and loses only the
-- attribution.
--
-- If you re-run it, MySQL will report that the table or column already exists.
-- That is harmless; nothing below is destructive.
--
-- GENERATED by scripts/gen-landing-migration.js — do not edit by hand.

-- 1. The table itself.
${table[0]};
${indexes.map((i) => i + '\n').join('')}
-- 2. Link orders to the landing page that produced them, for funnel reporting.
ALTER TABLE \`Order\` ADD COLUMN \`landingPageId\` VARCHAR(191) NULL;
ALTER TABLE \`Order\` ADD INDEX \`Order_landingPageId_idx\`(\`landingPageId\`);
ALTER TABLE \`Order\` ADD CONSTRAINT \`Order_landingPageId_fkey\`
  FOREIGN KEY (\`landingPageId\`) REFERENCES \`LandingPage\`(\`id\`) ON DELETE SET NULL ON UPDATE CASCADE;
`;

fs.writeFileSync('prisma/add-landing-pages.sql', header);
console.log('Wrote prisma/add-landing-pages.sql');
console.log(`  CREATE TABLE LandingPage (with its indexes inline) + 3 Order statements`);
