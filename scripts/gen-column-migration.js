/**
 * Generate the ALTER TABLE statements that widen every column whose type changed.
 *
 * Compares the committed DDL against the regenerated one and emits only the
 * differences, so the migration is derived from the schemas rather than typed by
 * hand and cannot drift from them.
 *
 * This matters because a live store cannot re-import schema.sql — that drops
 * every table. Widening a column is non-destructive in MySQL, so this is the
 * safe path for a database that already holds orders.
 */
const fs = require('fs');
const { execSync } = require('child_process');

const oldSql = execSync('git show HEAD:prisma/schema.sql', { encoding: 'utf8' });
const newSql = fs.readFileSync('prisma/schema.sql', 'utf8');

/** Pull `table -> { column -> fullDefinition }` out of a MySQL DDL dump. */
function parse(sql) {
  const out = {};
  const tableRe = /CREATE TABLE `(\w+)` \(([\s\S]*?)\n\)/g;
  let m;
  while ((m = tableRe.exec(sql))) {
    const [, table, body] = m;
    out[table] = {};
    for (const raw of body.split('\n')) {
      const line = raw.trim().replace(/,$/, '');
      const col = line.match(/^`(\w+)`\s+(.+)$/);
      if (!col) continue;
      const [, name, def] = col;
      // Skip index/key lines that start with a backtick-free keyword.
      if (/^(PRIMARY KEY|UNIQUE INDEX|INDEX|KEY|CONSTRAINT)/.test(name)) continue;
      out[table][name] = def;
    }
  }
  return out;
}

const before = parse(oldSql);
const after = parse(newSql);

const changes = [];
for (const [table, cols] of Object.entries(after)) {
  for (const [col, def] of Object.entries(cols)) {
    const prev = before[table]?.[col];
    if (prev === undefined) continue; // new column — not our concern here
    if (prev === def) continue;
    changes.push({ table, column: col, from: prev, to: def });
  }
}

if (!changes.length) {
  console.log('No column type changes detected.');
  process.exit(0);
}

const header = `-- Widen columns that Prisma created as VARCHAR(191)
--
-- Prisma maps a plain \`String\` to VARCHAR(191) on MySQL. SQLite does not enforce
-- that limit, so over-long values saved and read back correctly in development
-- and were silently truncated on MySQL. Where the value is JSON the truncation
-- makes it unparseable and the UI renders empty — the menu, the payment logos
-- and the product images all failed this way.
--
-- MySQL truncates on write, so data already lost cannot be recovered by this
-- script; it stops the loss from continuing. Re-save the affected records after
-- running it.
--
-- Widening a column is non-destructive and keeps every row. Run it in phpMyAdmin
-- (SQL tab) against the database named in DATABASE_URL. It is safe to run more
-- than once.
--
-- Generated by scripts/gen-column-migration.js — do not edit by hand.

`;

const statements = changes.map(
  (c) => `-- ${c.table}.${c.column}: ${c.from.split(' ').slice(0, 2).join(' ')} -> ${c.to.split(' ').slice(0, 2).join(' ')}\nALTER TABLE \`${c.table}\` MODIFY \`${c.column}\` ${c.to};`
);

const body = statements.join('\n\n') + '\n';

const out = 'prisma/fix-column-lengths.sql';
fs.writeFileSync(out, header + body);

console.log(`Wrote ${out} — ${changes.length} column(s)\n`);
for (const c of changes) {
  console.log(`  ${(c.table + '.' + c.column).padEnd(34)} ${c.from.split(' ').slice(0, 2).join(' ')}  ->  ${c.to.split(' ').slice(0, 2).join(' ')}`);
}
