/**
 * Generate prisma/fix-column-lengths.sql — the ALTER TABLE statements that widen
 * every column Prisma would create as VARCHAR(191).
 *
 *   node scripts/gen-column-migration.js
 *
 * Deliberately NOT a diff against git history. It was one, and that produced a
 * dangerous file: once the first batch of columns was committed, the diff against
 * HEAD contained only the *newly* changed column, so a merchant running it would
 * have fixed one column and silently missed the other eighty.
 *
 * Instead the source of truth is scripts/column-types.js — the canonical list of
 * columns needing an explicit MySQL native type — and every one is emitted,
 * unconditionally. Setting a column to the type it already has is a no-op in
 * MySQL, so the file is complete and safe to run repeatedly, against any version
 * of the schema.
 */
const fs = require('fs');

const columnTypes = require('./column-types');

const ddl = fs.readFileSync('prisma/schema.sql', 'utf8');

/** `table -> { column -> fullDefinition }` from the generated MySQL DDL. */
function parse(sql) {
  const out = {};
  const tableRe = /CREATE TABLE `(\w+)` \(([\s\S]*?)\n\)/g;
  let m;
  while ((m = tableRe.exec(sql))) {
    const [, table, body] = m;
    out[table] = {};
    for (const raw of body.split('\n')) {
      const line = raw.trim().replace(/,$/, '');
      const col = line.match(/^`(\w+)`\s+(.+)$/);
      if (!col) continue;
      out[table][col[1]] = col[2];
    }
  }
  return out;
}

const schema = parse(ddl);

const statements = [];
const missing = [];

for (const [table, fields] of Object.entries(columnTypes)) {
  for (const column of Object.keys(fields)) {
    const def = schema[table]?.[column];
    if (!def) {
      missing.push(`${table}.${column}`);
      continue;
    }
    statements.push({ table, column, def });
  }
}

if (missing.length) {
  console.error(
    `These columns are listed in scripts/column-types.js but not found in prisma/schema.sql:\n  ` +
      missing.join('\n  ') +
      `\n\nRegenerate the DDL first (npm run db:sql), or refresh the list (npm run db:column-types).`
  );
  process.exit(1);
}

const header = `-- Widen every column that Prisma would otherwise create as VARCHAR(191)
--
-- Prisma maps a plain \`String\` to VARCHAR(191) on MySQL. SQLite does not enforce
-- that limit, so over-long values saved and read back correctly in development
-- and were silently truncated on the server. Where the value is JSON the
-- truncation makes it unparseable and the interface renders empty — the menu,
-- the payment logos and the product images all failed this way.
--
-- ${statements.length} columns in total.
--
-- HOW TO RUN
--   hPanel -> Databases -> phpMyAdmin -> select your database -> SQL tab,
--   paste this whole file, press Go.
--
--   Widening a column is non-destructive and keeps every row. Do NOT re-import
--   schema.sql instead: that drops every table.
--
-- AFTERWARDS
--   MySQL truncates on write, so values already stored were lost when they were
--   saved. This stops the loss; it cannot restore what was cut. Open the menu,
--   the payment logos and any product you added, and save them again.
--   GET /api/health reports whether any critical column is still narrow.
--
-- Safe to run more than once: applying an ALTER that sets a column to the type
-- it already has is a no-op.
--
-- GENERATED by scripts/gen-column-migration.js — do not edit by hand.

`;

const body =
  statements.map(({ table, column, def }) => `ALTER TABLE \`${table}\` MODIFY \`${column}\` ${def};`).join('\n') + '\n';

fs.writeFileSync('prisma/fix-column-lengths.sql', header + body);

console.log(`Wrote prisma/fix-column-lengths.sql — ${statements.length} ALTER statement(s)`);
console.log('');
const byTable = {};
for (const s of statements) byTable[s.table] = (byTable[s.table] || 0) + 1;
for (const [t, n] of Object.entries(byTable).sort()) console.log(`  ${t.padEnd(16)} ${n}`);
