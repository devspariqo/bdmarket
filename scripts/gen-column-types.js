/**
 * Regenerate scripts/column-types.js from prisma/schema.prisma.
 *
 * Run this after adding or removing a `@db.Text` / `@db.LongText` annotation, so
 * the list the provider switcher uses stays in step with the schema.
 *
 *   node scripts/gen-column-types.js
 */
const fs = require('fs');

const schema = fs.readFileSync('prisma/schema.prisma', 'utf8');

const byModel = {};
let model = null;
for (const line of schema.split('\n')) {
  const m = line.match(/^model\s+(\w+)\s*\{/);
  if (m) {
    model = m[1];
    continue;
  }
  if (/^\}/.test(line)) {
    model = null;
    continue;
  }
  if (!model) continue;

  const field = line.match(/^\s+(\w+)\s+String\??\s+(@db\.(?:Text|LongText))/);
  if (!field) continue;

  byModel[model] = byModel[model] || {};
  byModel[model][field[1]] = field[2];
}

const count = Object.values(byModel).reduce((n, f) => n + Object.keys(f).length, 0);

const out = `/**
 * Which columns carry an explicit MySQL native type, and which one.
 *
 * Prisma maps a plain \`String\` to VARCHAR(191) on MySQL, which silently
 * truncates long values — including the JSON in \`Menu.items\`, \`Setting.value\`
 * and \`Product.images\`, where truncation makes the value unparseable and the UI
 * renders empty.
 *
 * The annotation is invalid on SQLite (\`Native type Text is not supported for
 * sqlite connector\`), so \`scripts/use-db.js\` strips these when switching to
 * SQLite and re-applies them for MySQL and Postgres. Without that, switching to
 * SQLite leaves a schema Prisma refuses to load.
 *
 * GENERATED by scripts/gen-column-types.js — do not edit by hand.
 * ${count} column(s) across ${Object.keys(byModel).length} model(s).
 */

module.exports = ${JSON.stringify(byModel, null, 2)};
`;

fs.writeFileSync('scripts/column-types.js', out);
console.log(`Wrote scripts/column-types.js — ${count} column(s) across ${Object.keys(byModel).length} model(s)`);
